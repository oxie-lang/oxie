/// The support module for a crate that has `std` where `cfg(std_cfg)` holds (always for
/// `None`): what needs `std` is left out without it.
pub fn runtime(std_cfg: Option<&str>) -> String {
    match std_cfg {
        // std's prelude has `String`, `Vec`, `Box` and `vec!`; without std, the support module's does
        None => RUNTIME_RS.lines().filter(|l| !l.contains("/*nostd*/")).map(|l| l.replacen("/*std*/ ", "", 1) + "\n").collect(),
        Some(c) => RUNTIME_RS.replace("/*std*/ ", &format!("#[cfg({})] ", c)).replace("/*nostd*/ ", &format!("#[cfg(not({}))] ", c)),
    }
}
