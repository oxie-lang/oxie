    fn max_by_key<K: PartialOrd, F: FnMut(&'a T) -> K>(&'a self, f: F) -> Option<&'a T>;
    fn min_by_key<K: PartialOrd, F: FnMut(&'a T) -> K>(&'a self, f: F) -> Option<&'a T>;
    fn sorted(&self) -> Vec<T>
    where
        T: PartialOrd + Clone;
    fn sorted_descending(&self) -> Vec<T>
    where
        T: PartialOrd + Clone;
