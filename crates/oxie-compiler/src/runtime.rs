/// An error with a message wrapped around its cause. Created by `.context("...")`.
#[derive(Debug)]
pub struct ContextError {
    context: String,
    source: Option<AnyError>,
}

impl fmt::Display for ContextError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.context)
    }
}

impl ::core::error::Error for ContextError {
    fn source(&self) -> Option<&(dyn ::core::error::Error + 'static)> {
        match &self.source {
            Some(e) => Some(&**e),
            None => None,
        }
    }
}

/// Adds a message to an error (`Result`) or turns a missing value (`Option`) into an error.
pub trait Context<T> {
    fn context<C: fmt::Display>(self, context: C) -> ::core::result::Result<T, AnyError>;
    fn with_context<C: fmt::Display, F: FnOnce() -> C>(self, f: F) -> ::core::result::Result<T, AnyError>;
}

impl<T, E: Into<AnyError>> Context<T> for ::core::result::Result<T, E> {
    #[inline]
    fn context<C: fmt::Display>(self, context: C) -> ::core::result::Result<T, AnyError> {
        match self {
            Ok(v) => Ok(v),
            Err(e) => Err(Box::new(ContextError { context: context.to_string(), source: Some(e.into()) })),
        }
    }
    #[inline]
    fn with_context<C: fmt::Display, F: FnOnce() -> C>(self, f: F) -> ::core::result::Result<T, AnyError> {
        match self {
            Ok(v) => Ok(v),
            Err(e) => Err(Box::new(ContextError { context: f().to_string(), source: Some(e.into()) })),
        }
    }
}

impl<T> Context<T> for ::core::option::Option<T> {
    #[inline]
    fn context<C: fmt::Display>(self, context: C) -> ::core::result::Result<T, AnyError> {
        match self {
            Some(v) => Ok(v),
            None => Err(Box::new(ContextError { context: context.to_string(), source: None })),
        }
    }
    #[inline]
    fn with_context<C: fmt::Display, F: FnOnce() -> C>(self, f: F) -> ::core::result::Result<T, AnyError> {
        match self {
            Some(v) => Ok(v),
            None => Err(Box::new(ContextError { context: f().to_string(), source: None })),
        }
    }
}

/// Prints an error and its causes to stderr (used by `fun main() throws`).
/*std*/ pub fn report<E: Into<AnyError>>(err: E) {
    let err: AnyError = err.into();
    let mut last = err.to_string();
    eprintln!("error: {}", last);
    let mut source = err.source();
    while let Some(s) = source {
        // a wrapper that shows its cause's text adds nothing
        let text = s.to_string();
        if text != last {
            eprintln!("  caused by: {}", text);
        }
        last = text;
        source = s.source();
    }
}
